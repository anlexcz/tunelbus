#!/usr/bin/env bash
set -euo pipefail

# Full, consistent SQLite snapshots compressed with Zstandard.
# This script does not migrate, modify, or delete legacy .sqlite3 backups.
DB="${TUNELBUS_DB:-/srv/anlex/tunelbus/data/tunelbus.sqlite3}"
BACKUP_ROOT="${TUNELBUS_BACKUP_ROOT:-/srv/anlex/tunelbus/backups}"
INTRADAY_DIR="$BACKUP_ROOT/intraday"
DAILY_DIR="$BACKUP_ROOT/daily"
MODE="${1:-}"

if [[ "$MODE" != "intraday" && "$MODE" != "daily" ]]; then
    echo "Usage: $0 {intraday|daily}" >&2
    exit 2
fi

for tool in sqlite3 zstd flock mktemp; do
    command -v "$tool" >/dev/null 2>&1 || { echo "ERROR: missing $tool" >&2; exit 1; }
done
[[ -f "$DB" ]] || { echo "ERROR: missing database $DB" >&2; exit 1; }

mkdir -p "$INTRADAY_DIR" "$DAILY_DIR"

# Prevent concurrent daily/intraday snapshots from consuming disk at once.
exec 9>"$BACKUP_ROOT/.backup.lock"
flock -x 9

if [[ "$MODE" == "intraday" ]]; then
    TIMESTAMP="$(date '+%Y-%m-%d_%H-%M-%S')"
    DESTINATION="$INTRADAY_DIR/tunelbus_$TIMESTAMP.sqlite3.zst"
else
    # 02:30 backup belongs to the previously completed calendar day.
    BACKUP_DATE="$(date -d 'yesterday' '+%Y-%m-%d')"
    DESTINATION="$DAILY_DIR/tunelbus_$BACKUP_DATE.sqlite3.zst"
fi

# Do not overwrite an already completed backup during repeated timer runs.
if [[ -e "$DESTINATION" ]]; then
    zstd -q -t "$DESTINATION"
    echo "Backup already exists and passes Zstandard check: $DESTINATION"
    exit 0
fi

WORK_DIR="$(dirname "$DESTINATION")"
TEMP_DB=""
TEMP_ZST=""
cleanup() {
    [[ -z "$TEMP_DB" ]] || rm -f -- "$TEMP_DB"
    [[ -z "$TEMP_ZST" ]] || rm -f -- "$TEMP_ZST"
}
trap cleanup EXIT

# A local temporary file keeps SQLite Backup API snapshots consistent.
TEMP_DB="$(mktemp "$WORK_DIR/.tunelbus-snapshot.XXXXXXXX.sqlite3")"
TEMP_ZST="$(mktemp "$WORK_DIR/.tunelbus-compressed.XXXXXXXX.zst")"

# sqlite3 .backup uses the online backup API; filenames are generated by this script.
sqlite3 "$DB" ".backup '$TEMP_DB'"

# immutable=1 avoids generating -wal/-shm sidecars for a completed snapshot.
CHECK="$(sqlite3 "file:$TEMP_DB?immutable=1" 'PRAGMA integrity_check;')"
if [[ "$CHECK" != "ok" ]]; then
    echo "ERROR: SQLite integrity check failed: $CHECK" >&2
    exit 1
fi

zstd -q -1 -T1 -c "$TEMP_DB" > "$TEMP_ZST"
zstd -q -t "$TEMP_ZST"

# Publish only after SQLite integrity and compressed-stream validation succeed.
chmod 0640 "$TEMP_ZST"
# Same-filesystem hard link publishes atomically and refuses an existing target.
# Unlike mv -n, this fails loudly rather than silently skipping publication.
ln -- "$TEMP_ZST" "$DESTINATION"
rm -f -- "$TEMP_ZST"
TEMP_ZST=""

# Never delete pre-existing uncompressed backups automatically.
# For new compressed snapshots, preserve the original 14-day age-based
# policy, only after a successfully validated daily backup.
if [[ "$MODE" == "daily" ]]; then
    find "$INTRADAY_DIR" -maxdepth 1 -type f \
        -name "tunelbus_${BACKUP_DATE}_*.sqlite3.zst" -delete
    find "$DAILY_DIR" -maxdepth 1 -type f \
        -name 'tunelbus_*.sqlite3.zst' -mtime +14 -delete
fi

echo "$MODE backup created, SQLite integrity and Zstandard stream verified: $DESTINATION"
